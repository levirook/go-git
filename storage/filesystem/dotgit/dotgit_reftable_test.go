// newReftableFS creates a temporary filesystem with a reftable-based git repository.
// The repository contains:
//   - HEAD -> refs/heads/master (symref)
//   - refs/heads/master -> b374b232173e3d52f8835192b802e7904357526b
//   - refs/tags/v1.0 -> b374b232173e3d52f8835192b802e7904357526b
func newReftableFS(t testing.TB) *DotGit {
	t.Helper()

	fs := osfs.New(t.TempDir())

	// Write the config file with extensions.refStorage = reftable.
	config := "[core]\n\trepositoryformatversion = 1\n\tfilemode = true\n\tbare = false\n[extensions]\n\trefstorage = reftable\n"
	err := util.WriteFile(fs, "config", []byte(config), 0o644)
	require.NoError(t, err)

	// Write the HEAD placeholder (as git does for reftable repos).
	err = util.WriteFile(fs, "HEAD", []byte("ref: refs/heads/.invalid\n"), 0o644)
	require.NoError(t, err)

	// Create reftable directory and files.
	err = fs.MkdirAll("reftable", os.ModeDir|os.ModePerm)
	require.NoError(t, err)

	mainName := "0x000000000001-0x000000000004-1bf8ff16.ref"
	tagName := "0x000000000005-0x000000000005-76f0b0bc.ref"

	err = util.WriteFile(fs, fs.Join("reftable", mainName), reftableMainTableData, 0o644)
	require.NoError(t, err)

	err = util.WriteFile(fs, fs.Join("reftable", tagName), reftableTagTableData, 0o644)
	require.NoError(t, err)

	tablesList := mainName + "\n" + tagName + "\n"
	err = util.WriteFile(fs, fs.Join("reftable", "tables.list"), []byte(tablesList), 0o644)
	require.NoError(t, err)

	// Write the refs/ placeholder files that git creates in reftable repos.
	err = util.WriteFile(fs, fs.Join("refs", "heads"), []byte("this repository uses the reftable format\n"), 0o644)
	require.NoError(t, err)

	return New(fs)
}

func TestReftableIsReftable(t *testing.T) {
	t.Parallel()

	dir := newReftableFS(t)
	assert.True(t, dir.isReftable())
}

func TestReftableRefs(t *testing.T) {
	t.Parallel()

	dir := newReftableFS(t)
	refs, err := dir.Refs()
	require.NoError(t, err)

	refMap := make(map[string]*plumbing.Reference)
	for _, r := range refs {
		refMap[r.Name().String()] = r
	}

	// HEAD should be a symref pointing to refs/heads/master.
	head, ok := refMap["HEAD"]
	require.True(t, ok, "HEAD not found")
	assert.Equal(t, plumbing.SymbolicReference, head.Type())
	assert.Equal(t, plumbing.ReferenceName("refs/heads/master"), head.Target())

	// refs/heads/master should be a hash ref.
	master, ok := refMap["refs/heads/master"]
	require.True(t, ok, "refs/heads/master not found")
	assert.Equal(t, plumbing.HashReference, master.Type())
	assert.Equal(t, "b374b232173e3d52f8835192b802e7904357526b", master.Hash().String())

	// refs/tags/v1.0 should be a hash ref.
	tag, ok := refMap["refs/tags/v1.0"]
	require.True(t, ok, "refs/tags/v1.0 not found")
	assert.Equal(t, plumbing.HashReference, tag.Type())
	assert.Equal(t, "b374b232173e3d52f8835192b802e7904357526b", tag.Hash().String())
}

func TestReftableRef(t *testing.T) {
	t.Parallel()

	dir := newReftableFS(t)

	// Look up HEAD.
	ref, err := dir.Ref("HEAD")
	require.NoError(t, err)
	assert.Equal(t, plumbing.SymbolicReference, ref.Type())
	assert.Equal(t, plumbing.ReferenceName("refs/heads/master"), ref.Target())

	// Look up refs/heads/master.
	ref, err = dir.Ref("refs/heads/master")
	require.NoError(t, err)
	assert.Equal(t, plumbing.HashReference, ref.Type())
	assert.Equal(t, "b374b232173e3d52f8835192b802e7904357526b", ref.Hash().String())

	// Non-existent ref returns ErrReferenceNotFound.
	_, err = dir.Ref("refs/heads/nonexistent")
	assert.ErrorIs(t, err, plumbing.ErrReferenceNotFound)
}

func TestReftableCountLooseRefs(t *testing.T) {
	t.Parallel()

	dir := newReftableFS(t)
	count, err := dir.CountLooseRefs()
	require.NoError(t, err)
	assert.Equal(t, 0, count)
}

func TestReftableSetRefNotSupported(t *testing.T) {
	t.Parallel()

	dir := newReftableFS(t)
	ref := plumbing.NewHashReference("refs/heads/new", plumbing.ZeroHash)
	err := dir.SetRef(ref, nil)
	assert.ErrorIs(t, err, ErrReftableNotSupported)
}

func TestReftableRemoveRefNotSupported(t *testing.T) {
	t.Parallel()

	dir := newReftableFS(t)
	err := dir.RemoveRef("refs/heads/master")
	assert.ErrorIs(t, err, ErrReftableNotSupported)
}

func TestReftablePackRefsNotSupported(t *testing.T) {
	t.Parallel()

	dir := newReftableFS(t)
	err := dir.PackRefs()
	assert.ErrorIs(t, err, ErrReftableNotSupported)
}
